function ddStat(item, key){ const arr = item['stats_'+lang] || []; const f = arr.find(s=>s.label===key); return f ? f.value : ''; }

async function loadDDContent() {
  try {
    const res = await fetch(DD_API, { cache: 'no-store' });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || 'Request failed');
    DD_ITEMS = data.items || [];
    renderDDContent();
  } catch (e) { /* бэкенд недоступен — секции останутся пустыми до заполнения в админке */ }
}

function ddRenderCard(item) {
  const title = ddEsc(item['title_'+lang] || item.title_ru);
  const price = ddStat(item, 'price');
  const unit = ddStat(item, 'unit');
  const priceBlock = price ? `<div class="price-block"><div class="price">${ddEsc(price)}</div><div class="price-sub">${ddEsc(unit)}</div></div>` : '';
  const desc = item['description_'+lang] || item.description_ru;
  const reqs = item['requirements_'+lang] || [];
  const note = item['note_'+lang] || item.note_ru || '';
  const wide = item.featured ? ' wide featured' : '';
  const descHtml = desc ? `<div class="service-description"><p>${ddEsc(desc)}</p></div>` : '';
  const listHtml = reqs.length ? `<ul${item.featured?' class="two-col-list"':''}>${reqs.map(r=>`<li>${ddEsc(r)}</li>`).join('')}</ul>` : '';
  const noteHtml = note ? `<div class="premium-note">${ddEsc(note)}</div>` : '';
  return `<div class="service-box${wide}"><div class="service-top"><h2>${title}</h2>${priceBlock}</div>${descHtml}${listHtml}${noteHtml}</div>`;
}

function renderDDContent() {
  const byCat = c => DD_ITEMS.filter(i => i.filter_cat === c);
  const hero = byCat('hero')[0];
  if (hero) {
    const t = hero['title_'+lang] || hero.title_ru;
    const d = hero['description_'+lang] || hero.description_ru;
    if (t) document.getElementById('heroTitle').textContent = t;
    if (d) document.getElementById('heroSub').textContent = d;
    if (hero.image) {
    const heroEl = document.getElementById('heroImg');
    if (/\.(mp4|webm|mov)$/i.test(hero.image)) {
      const v = document.createElement('video');
      v.id = 'heroImg'; v.className = heroEl.className;
      v.autoplay = true; v.muted = true; v.loop = true; v.playsInline = true;
      v.src = hero.image;
      heroEl.replaceWith(v);
    } else {
      heroEl.src = hero.image;
    }
  }
  }
  const features = byCat('feature');
  document.getElementById('featureContainer').innerHTML = features.length ? features.map(ddRenderCard).join('') : '';
  const pricing = byCat('pricing');
  document.getElementById('pricingContainer').innerHTML = pricing.length ? pricing.map(ddRenderCard).join('') : '';

  const steps = byCat('step');
  if (steps.length) {
    const rows = steps.map((s,i)=>`<div class="row"><span>${ddEsc(s['title_'+lang]||s.title_ru)}</span><span class="row-val">${ddEsc(s.area||String(i+1).padStart(2,'0'))}</span></div>`).join('');
    document.getElementById('stepsContainer').innerHTML = `<div class="service-box full"><div class="service-top"><h2>${lang==='ru'?'Программа дня с дизайнером':'Design Day Schedule'}</h2></div><div class="service-text">${rows}</div></div>`;
  }
  const objects = byCat('object');
  if (objects.length) {
    const rows = objects.map(o=>`<div class="row"><span>${ddEsc(o['title_'+lang]||o.title_ru)}</span></div>`).join('');
    document.getElementById('objectsContainer').innerHTML = `<div class="service-box"><div class="service-top"><h2>${lang==='ru'?'Для каких ситуаций':'Suitable Situations'}</h2></div><div class="service-text">${rows}</div></div>`;
  }
  const report = byCat('report');
  if (report.length) {
    const items = report.map(r=>`<li>${ddEsc(r['title_'+lang]||r.title_ru)}</li>`).join('');
    const note = report[0]['note_'+lang] || report[0].note_ru || '';
    document.getElementById('reportContainer').innerHTML = `<div class="service-box"><div class="service-top"><h2>${lang==='ru'?'Что вы получаете':'What You Get'}</h2></div><ul>${items}</ul>${note?`<div class="premium-note">${ddEsc(note)}</div>`:''}</div>`;
  }
  const result = byCat('result')[0];
  if (result) {
    const text = result['description_'+lang] || result.description_ru;
    document.getElementById('resultContainer').innerHTML = `<div class="service-box full featured"><div class="service-top"><h2>${ddEsc(result['title_'+lang]||result.title_ru)}</h2></div><div class="result-block"><div class="result-icon">✦</div><p>${text}</p></div></div>`;
  }
}

const _origSetLangDD = setLang;
window.setLang = function(l) { _origSetLangDD(l); if (DD_ITEMS.length) renderDDContent(); };

loadDDContent();
