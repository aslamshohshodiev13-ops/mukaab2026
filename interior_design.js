const INT_API = "mukaab-admin-backend/public/list.php?type=interior";
let INT_ITEMS = [];

function intEsc(s){return (s??'').toString().replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]))}
function intStat(item, key){ const arr = item['stats_'+lang] || []; const f = arr.find(s=>s.label===key); return f ? f.value : ''; }

function intRenderCard(item) {
  const title = intEsc(item['title_'+lang] || item.title_ru);
  const price = intStat(item, 'price');
  const unit = intStat(item, 'unit');
  const priceBlock = price ? `<div class="price-block"><div class="price">${intEsc(price)}</div><div class="price-sub">${intEsc(unit)}</div></div>` : '';
  const desc = item['description_'+lang] || item.description_ru;
  const reqs = item['requirements_'+lang] || [];
  const note = item['note_'+lang] || item.note_ru || '';
  const wide = item.featured ? ' wide featured' : '';
  const descHtml = desc ? `<div class="service-description"><p>${intEsc(desc)}</p></div>` : '';
  const listHtml = reqs.length ? `<ul${item.featured?' class="two-col-list"':''}>${reqs.map(r=>`<li>${intEsc(r)}</li>`).join('')}</ul>` : '';
  const noteHtml = note ? `<div class="premium-note">${intEsc(note)}</div>` : '';
  return `<div class="service-box${wide}"><div class="service-top"><h2>${title}</h2>${priceBlock}</div>${descHtml}${listHtml}${noteHtml}</div>`;
}

async function loadIntContent() {
  try {
    const res = await fetch(INT_API, { cache: 'no-store' });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || 'Request failed');
    INT_ITEMS = data.items || [];
    renderIntContent();
  } catch (e) { /* бэкенд недоступен — секции останутся пустыми до заполнения в админке */ }
}

function renderIntContent() {
  const byCat = c => INT_ITEMS.filter(i => i.filter_cat === c);
  const hero = byCat('hero')[0];
  if (hero) {
    const t = hero['title_'+lang] || hero.title_ru;
    const d = hero['description_'+lang] || hero.description_ru;
    if (t) document.getElementById('heroTitle').textContent = t;
    if (d) document.getElementById('heroSub').textContent = d;
    if (hero.image) {
    const heroEl = document.getElementById('heroImg');
    if (/\.(mp4|webm|mov)$/i.test(hero.image)) {
      const v = document.createElement('video');
      v.id = 'heroImg'; v.className = heroEl.className;
      v.autoplay = true; v.muted = true; v.loop = true; v.playsInline = true;
      v.src = hero.image;
      heroEl.replaceWith(v);
    } else {
      heroEl.src = hero.image;
    }
  }
  }
  const design = byCat('design');
  document.getElementById('designContainer').innerHTML = design.length ? design.map(intRenderCard).join('') : '';
  const style = byCat('style');
  document.getElementById('styleContainer').innerHTML = style.length ? style.map(intRenderCard).join('') : '';
}

const _origSetLangInt = setLang;
window.setLang = function(l) { _origSetLangInt(l); if (INT_ITEMS.length) renderIntContent(); };

loadIntContent();
