const VIZ_API = "mukaab-admin-backend/public/list.php?type=viz";
let VIZ_ITEMS = [];

function vzEsc(s){return (s??'').toString().replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]))}
function vzStat(item, key){ const arr = item['stats_'+lang] || []; const f = arr.find(s=>s.label===key); return f ? f.value : ''; }

function vzRenderCard(item) {
  const title = vzEsc(item['title_'+lang] || item.title_ru);
  const price = vzStat(item, 'price');
  const unit = vzStat(item, 'unit');
  const priceBlock = price ? `<div class="price-block"><div class="price">${vzEsc(price)}</div><div class="price-sub">${vzEsc(unit)}</div></div>` : '';
  const desc = item['description_'+lang] || item.description_ru;
  const reqs = item['requirements_'+lang] || [];
  const note = item['note_'+lang] || item.note_ru || '';
  const wide = item.featured ? ' wide featured' : (reqs.length && !desc ? '' : '');
  const descHtml = desc ? `<div class="service-description"><p>${vzEsc(desc)}</p></div>` : '';
  const listHtml = reqs.length ? `<ul${item.featured?' class="two-col-list"':''}>${reqs.map(r=>`<li>${vzEsc(r)}</li>`).join('')}</ul>` : '';
  const noteHtml = note ? `<div class="premium-note">${vzEsc(note)}</div>` : '';
  return `<div class="service-box${wide}"><div class="service-top"><h2>${title}</h2>${priceBlock}</div>${descHtml}${listHtml}${noteHtml}</div>`;
}

