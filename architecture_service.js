// ══════════════════════════════════════════════════════════
const ARC_API = "mukaab-admin-backend/public/list.php?type=architecture";
let ARC_ITEMS = [];

function arcEsc(s){return (s??'').toString().replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]))}
function arcStat(item, key){ const arr = item['stats_'+lang] || []; const f = arr.find(s=>s.label===key); return f ? f.value : ''; }

function arcRenderCard(item) {
  const title = arcEsc(item['title_'+lang] || item.title_ru);
  const price = arcStat(item, 'price');
  const unit = arcStat(item, 'unit');
  const priceBlock = price ? `<div class="price-block"><div class="price">${arcEsc(price)}</div><div class="price-sub">${arcEsc(unit)}</div></div>` : '';
  const desc = item['description_'+lang] || item.description_ru;
  const reqs = item['requirements_'+lang] || [];
  const note = item['note_'+lang] || item.note_ru || '';
  const wide = item.featured ? ' wide featured' : '';
  const descHtml = desc ? `<div class="service-description"><p>${arcEsc(desc)}</p></div>` : '';
  const listHtml = reqs.length ? `<ul${item.featured?' class="two-col-list"':''}>${reqs.map(r=>`<li>${arcEsc(r)}</li>`).join('')}</ul>` : '';
  const noteHtml = note ? `<div class="premium-note">${arcEsc(note)}</div>` : '';
  return `<div class="service-box${wide}"><div class="service-top"><h2>${title}</h2>${priceBlock}</div>${descHtml}${listHtml}${noteHtml}</div>`;
}

async function loadArcContent() {
  try {
    const res = await fetch(ARC_API, { cache: 'no-store' });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || 'Request failed');
    ARC_ITEMS = data.items || [];
    renderArcContent();
  } catch (e) { /* бэкенд недоступен — секции останутся пустыми до заполнения в админке */ }
}

function renderArcContent() {
  const byCat = c => ARC_ITEMS.filter(i => i.filter_cat === c);
  const hero = byCat('hero')[0];
  if (hero) {
    const t = hero['title_'+lang] || hero.title_ru;
    const d = hero['description_'+lang] || hero.description_ru;
    if (t) document.getElementById('heroTitle').textContent = t;
    if (d) document.getElementById('heroSub').textContent = d;
    if (hero.image) {
    const heroEl = document.getElementById('heroImg');
    if (/\.(mp4|webm|mov)$/i.test(hero.image)) {
      const v = document.createElement('video');
      v.id = 'heroImg'; v.className = heroEl.className;
      v.autoplay = true; v.muted = true; v.loop = true; v.playsInline = true;
      v.src = hero.image;
      heroEl.replaceWith(v);
    } else {
      heroEl.src = hero.image;
    }
  }
  }
  const design = byCat('design');
  document.getElementById('designContainer').innerHTML = design.length ? design.map(arcRenderCard).join('') : '';
  const viz3d = byCat('viz3d');
  document.getElementById('viz3dContainer').innerHTML = viz3d.length ? viz3d.map(arcRenderCard).join('') : '';
  const metal = byCat('metal');
  document.getElementById('metalContainer').innerHTML = metal.length ? metal.map(arcRenderCard).join('') : '';

  const materials = byCat('material');
  const matGrid = document.getElementById('materialsGrid');
  const matCard = document.getElementById('materialsCard');
  if (materials.length) {
    matCard.style.display = '';
    matGrid.innerHTML = materials.map(m => `<div class="mat-item"><div class="mat-name">${arcEsc(m['title_'+lang]||m.title_ru)}</div><div class="mat-desc">${arcEsc(m['description_'+lang]||m.description_ru)}</div></div>`).join('');
  } else {
    matCard.style.display = 'none';
  }
}

const _origSetLangArc = setLang;
window.setLang = function(l) { _origSetLangArc(l); if (ARC_ITEMS.length) renderArcContent(); };

loadArcContent();
